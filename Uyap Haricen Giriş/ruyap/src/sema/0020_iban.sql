-- IBAN kayıtları (26.11.2026). "Borçlu Tarafından Yapılan Ödemelerin Hesaba Aktarılması" talebi (UYAP genel talep,
-- talepKodu 14) için: vekil IBAN'ları büro genelinde birden çok kayıt; alacaklı IBAN'ı dosya başına bir kayıt.
-- UYAP'ın kendi "IBAN Bilgilerim" listesi IBAN'ı yıldızlı döndürdüğü için oradan alınamaz; bu tablolar tek kaynaktır.

CREATE TABLE IF NOT EXISTS avukat_iban (
    id           bigint       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    iban         varchar(34)  NOT NULL UNIQUE,          -- boşluksuz, büyük harf ("TR" + 24 hane)
    etiket       varchar(120) NOT NULL DEFAULT '',      -- ör. "Av. … — Ziraat"
    varsayilan   boolean      NOT NULL DEFAULT false,
    olusturulma  timestamptz  NOT NULL DEFAULT now()
);
-- En çok bir varsayılan IBAN
CREATE UNIQUE INDEX IF NOT EXISTS ux_avukat_iban_varsayilan ON avukat_iban (varsayilan) WHERE varsayilan;

-- Dosya künyesiyle (UYAP birim kimliği + dosya no) anahtarlanır: dosya büro veritabanına alınmamış olsa da çalışır.
CREATE TABLE IF NOT EXISTS dosya_alacakli_iban (
    birim_id     varchar(40)  NOT NULL,
    dosya_no     varchar(60)  NOT NULL,
    iban         varchar(34)  NOT NULL,
    birim_adi    varchar(255) NOT NULL DEFAULT '',
    guncelleme   timestamptz  NOT NULL DEFAULT now(),
    PRIMARY KEY (birim_id, dosya_no)
);
