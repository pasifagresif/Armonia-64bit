-- Mernis adresi ve yeniden tebliğ talebi (23.11.2026; Python: UyapMasa/modules/teblig_21_2_core.py,
-- uyap_core/teblig_212/gonder.py).
--
-- Ödeme emri İADE dönen borçlunun Mernis adresi UYAP'tan sorgulanır (borclu_bilgileri_goruntule_mernis.ajx) ve İLK
-- giden fiziki ödeme emri tebligatının adresiyle (zarf PDF'inden) karşılaştırılır:
--   kategori  uygun : adresler aynı → T.K. 21/2 şerhli yeniden tebliğ
--             farkli: tebligat Mernis adresine hiç çıkmamış → Mernis adresine normal tebligat
--             elle  : adres okunamadı / ödeme emri zarfı yok / Mernis kaydı yok (nedeni `aciklama`da)
-- Sorgu sonucu borçlunun dosyadaki kaydına (dosya_taraf) yazılır; aynı kişi başka dosyada yakın zamanda sorgulandıysa
-- UYAP'a yeniden sorulmaz (sonuç kopyalanır).
CREATE TABLE IF NOT EXISTS borclu_mernis (
    dosyataraf_id  bigint       PRIMARY KEY REFERENCES dosya_taraf(id) ON DELETE CASCADE,
    adres          text         NOT NULL DEFAULT '',
    mahalle        varchar(200) NOT NULL DEFAULT '',
    sokak          varchar(200) NOT NULL DEFAULT '',
    dis_no         varchar(40)  NOT NULL DEFAULT '',
    ic_no          varchar(40)  NOT NULL DEFAULT '',
    ilce           varchar(100) NOT NULL DEFAULT '',
    il             varchar(100) NOT NULL DEFAULT '',
    ham_yanit      jsonb        NULL,
    zaman          timestamptz  NOT NULL DEFAULT now(),
    tebligat_id    bigint       NULL REFERENCES tebligat_barkod(id) ON DELETE SET NULL,
    teblig_adresi  text         NOT NULL DEFAULT '',
    kategori       varchar(12)  NOT NULL DEFAULT '' CHECK (kategori IN ('', 'uygun', 'farkli', 'elle')),
    aciklama       text         NOT NULL DEFAULT ''
);

-- Gönderilen (ya da gönderilmeden sonuçlanan) yeniden tebliğ talepleri; her deneme bir satır. Gönderim ÜCRETLİDİR.
--   tur    2: T.K. 21/2 şerhli, 1: normal tebligat (ikisi de Mernis adresine)
--   sonuc  gonderildi: UYAP kabul etti · zaten: dosyada talep evrakı var, gönderilmedi · hata: gönderilemedi
CREATE TABLE IF NOT EXISTS yeniden_teblig_talebi (
    id             bigint        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dosyataraf_id  bigint        NOT NULL REFERENCES dosya_taraf(id) ON DELETE CASCADE,
    zaman          timestamptz   NOT NULL DEFAULT now(),
    tur            smallint      NOT NULL CHECK (tur IN (1, 2)),
    tutar          numeric(10,2) NOT NULL DEFAULT 0,
    sonuc          varchar(12)   NOT NULL CHECK (sonuc IN ('gonderildi', 'zaten', 'hata')),
    mesaj          text          NOT NULL DEFAULT ''
);
CREATE INDEX IF NOT EXISTS yeniden_teblig_talebi_taraf ON yeniden_teblig_talebi (dosyataraf_id, zaman DESC);
