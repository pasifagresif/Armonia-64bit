-- Dosya listeleri (23.11.2026, kullanıcı isteği). Süzgeçlerle bulunan dosyalar adlı bir listeye eklenir; sonra her
-- sekmede (Dosya Listesi, Kesinleştirme, Süreçler, Tebligatlar) liste seçilerek yalnız o dosyalar görüntülenir, o
-- sekmenin kendi süzgeçleri bunun içinde çalışır ve toplu taramalar yalnız listedeki dosyalara gider. Liste SABİTTİR:
-- eklenen dosyalar kalır, sonradan süzgece uyan dosyalar kendiliğinden girmez. Büro ortak (herkes görür).
CREATE TABLE IF NOT EXISTS dosya_listesi (
    id           bigint       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ad           text         NOT NULL,
    aciklama     text         NOT NULL DEFAULT '',
    olusturulma  timestamptz  NOT NULL DEFAULT now(),
    guncelleme   timestamptz  NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX IF NOT EXISTS uq_dosya_listesi_ad ON dosya_listesi (lower(ad));

CREATE TABLE IF NOT EXISTS dosya_listesi_uyesi (
    liste_id  bigint       NOT NULL REFERENCES dosya_listesi(id) ON DELETE CASCADE,
    dosya_id  bigint       NOT NULL REFERENCES dosya(id) ON DELETE CASCADE,
    eklenme   timestamptz  NOT NULL DEFAULT now(),
    PRIMARY KEY (liste_id, dosya_id)
);
CREATE INDEX IF NOT EXISTS ix_dosya_listesi_uyesi_dosya ON dosya_listesi_uyesi (dosya_id);
