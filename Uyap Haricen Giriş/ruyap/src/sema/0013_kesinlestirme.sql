-- UYAP'ın bildirdiği kesinleşme: programın hesabı (kesinlesme_durumu) "süre doldu, kesinleştirilebilir" demektir;
-- icra dairesinin takibi UYAP'ta gerçekten kesinleştirip kesinleştirmediği ayrıca UYAP'tan okunur
-- (getTakibiKesinlesenBorcluListesi_brd.ajx: dosyada takibi kesinleşmiş borçlular; talepten hemen önce
-- dosya_icra_kesinlesme.ajx). Daire kesinleştirmeyi kendiliğinden de yapabilir.
--   uyap_kesinlesti          NULL: hiç sorulmadı; true / false: son sorgunun sonucu
--   uyap_kesinlesme_zamani   son sorgunun zamanı
--   uyap_kesinlesti_gunu     UYAP'ta kesinleşmiş İLK görüldüğü gün (sonraki sorgular değiştirmez)
ALTER TABLE dosya_taraf ADD COLUMN IF NOT EXISTS uyap_kesinlesti boolean NULL;
ALTER TABLE dosya_taraf ADD COLUMN IF NOT EXISTS uyap_kesinlesme_zamani timestamptz NULL;
ALTER TABLE dosya_taraf ADD COLUMN IF NOT EXISTS uyap_kesinlesti_gunu date NULL;

-- Gönderilen (ya da gönderilmeden sonuçlanan) kesinleştirme talepleri; her deneme bir satır.
--   sonuc  gonderildi : UYAP gönderimi kabul etti
--          kesinlesmis: UYAP borçlunun zaten kesinleşmiş olduğunu bildirdi, talep gönderilmedi
--          tur_yok    : UYAP'ın genel talep listesinde "Takibin Kesinleşmesi" yok (dosya durumu izin vermiyor)
--          hata       : hazırlama / imza / gönderim başarısız (mesajda neden)
CREATE TABLE IF NOT EXISTS kesinlestirme_talebi (
    id             bigint       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dosyataraf_id  bigint       NOT NULL REFERENCES dosya_taraf(id) ON DELETE CASCADE,
    zaman          timestamptz  NOT NULL DEFAULT now(),
    sonuc          varchar(12)  NOT NULL CHECK (sonuc IN ('gonderildi', 'kesinlesmis', 'tur_yok', 'hata')),
    mesaj          text         NOT NULL DEFAULT ''
);
CREATE INDEX IF NOT EXISTS kesinlestirme_talebi_taraf ON kesinlestirme_talebi (dosyataraf_id, zaman DESC);
