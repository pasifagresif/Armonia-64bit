-- Elle mazbata bağı (23.11.2026). Fiziki tebligatın mazbatası çoğu zaman fotoğraf olarak taranıp
-- "Kapalı Tebliğ Mazbatası" / açıklamasında barkod olmayan "Tebliğ Mazbatası" diye dosyaya girer; hangi tebligata
-- ait olduğu otomatik kurulamaz (Mazbatalar::bul yalnız TEK aday kalınca bağlar). Kullanıcı dosya panelinde sağ tıkla
-- bağlar. Bağ evrak numaralarıyla tutulur (taramalar tebligat satırını yeniden yazsa da kalır); elle bağ otomatik
-- eşleşmeden önce gelir ve bağlanan mazbata başka tebligata aday olmaz.
CREATE TABLE IF NOT EXISTS tebligat_mazbata_bagi (
    id                 bigint       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dosya_id           bigint       NOT NULL REFERENCES dosya(id) ON DELETE CASCADE,
    tebligat_evrak_no  integer      NOT NULL,
    mazbata_evrak_no   integer      NOT NULL,
    zaman              timestamptz  NOT NULL DEFAULT now(),
    CONSTRAINT uq_mazbata_bagi_tebligat UNIQUE (dosya_id, tebligat_evrak_no),
    CONSTRAINT uq_mazbata_bagi_mazbata UNIQUE (dosya_id, mazbata_evrak_no)
);
