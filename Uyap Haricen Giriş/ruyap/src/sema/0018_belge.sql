-- Büro belge deposu (24.11.2026, plan docs/claude-notlar/planlar/yazi-cokluuyap.md 2. aşama).
-- Armonia Yazı'da yazılan belgeler büro veritabanına kaydedilir: her kayıt bir sürüm; baytlar ofis diskinde
-- içerik adresli (%LOCALAPPDATA%\CokluUyap\ekler\<sha256>, iş ekleriyle aynı depo). Belge bir dosyaya bağlıdır
-- (yoksa künye metinleri boş) ve İş Listesi işlerine eklenebilir; onay iş üzerinden yürür.
-- Yetki (kullanıcı kararı 24.11): oluşturan + bağlı işlerin sorumlusu / onaylayıcısı / izleyicisi + yöneticiler.

CREATE TABLE IF NOT EXISTS belge (
    id            bigint       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ad            varchar(200) NOT NULL,
    bicim         varchar(8)   NOT NULL DEFAULT 'udf' CHECK (bicim IN ('udf', 'docx')),
    dosya_id      bigint       NULL REFERENCES dosya(id) ON DELETE SET NULL,
    -- Dosya künyesi (dosya satırı yokken ya da silinince de gösterilir) ve UYAP kart bilgisi (gönderim için)
    birim_adi     varchar(255) NOT NULL DEFAULT '',
    dosya_no      varchar(60)  NOT NULL DEFAULT '',
    uyap_karti    jsonb        NULL,
    olusturan_id  bigint       NULL REFERENCES kullanici(id) ON DELETE SET NULL,
    son_surum     integer      NOT NULL DEFAULT 0,
    imzali        boolean      NOT NULL DEFAULT false,  -- son sürüm e-imzalı mı
    gonderim      jsonb        NULL,                    -- son UYAP gönderimi: {zaman, tur, tur_adi, mesaj, kisi}
    silindi       timestamptz  NULL,
    arama_metni   text         NOT NULL DEFAULT '',     -- ad + künye, Türkçe küçük harf
    olusturulma   timestamptz  NOT NULL DEFAULT now(),
    guncelleme    timestamptz  NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS ix_belge_dosya ON belge (dosya_id) WHERE silindi IS NULL;
CREATE INDEX IF NOT EXISTS ix_belge_olusturan ON belge (olusturan_id) WHERE silindi IS NULL;

CREATE TABLE IF NOT EXISTS belge_surum (
    belge_id     bigint       NOT NULL REFERENCES belge(id) ON DELETE CASCADE,
    surum        integer      NOT NULL CHECK (surum >= 1),
    sha256       varchar(64)  NOT NULL,
    boyut        bigint       NOT NULL CHECK (boyut >= 0),
    imzali       boolean      NOT NULL DEFAULT false,
    kaydeden_id  bigint       NULL REFERENCES kullanici(id) ON DELETE SET NULL,
    notu         varchar(300) NOT NULL DEFAULT '',
    olusturulma  timestamptz  NOT NULL DEFAULT now(),
    PRIMARY KEY (belge_id, surum)
);
CREATE INDEX IF NOT EXISTS ix_belge_surum_sha ON belge_surum (sha256);

-- İş ↔ belge (bir belge birden çok işe, bir işe birden çok belge)
CREATE TABLE IF NOT EXISTS gorev_belge (
    gorev_id     bigint      NOT NULL REFERENCES gorev(id) ON DELETE CASCADE,
    belge_id     bigint      NOT NULL REFERENCES belge(id) ON DELETE CASCADE,
    ekleyen_id   bigint      NULL REFERENCES kullanici(id) ON DELETE SET NULL,
    olusturulma  timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (gorev_id, belge_id)
);
CREATE INDEX IF NOT EXISTS ix_gorev_belge_belge ON gorev_belge (belge_id);
